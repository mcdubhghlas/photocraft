const H0: u64 = 0xcbf29ce484222325;

fn fnv(h: &mut u64, b: &[u8]) {
    for &x in b {
        *h ^= u64::from(x);
        *h = h.wrapping_mul(0x100000001b3);
    }
}
fn hf32(h: &mut u64, v: f32) {
    fnv(h, &v.to_bits().to_le_bytes());
}
fn hf64(h: &mut u64, v: f64) {
    fnv(h, &v.to_bits().to_le_bytes());
}
fn hu32(h: &mut u64, v: u32) {
    fnv(h, &v.to_le_bytes());
}
fn x32(v: f32) -> String {
    format!("{:08x}", v.to_bits())
}
fn x64(v: f64) -> String {
    format!("{:016x}", v.to_bits())
}
/// Spaces and other awkward bytes in names are written as `\xNN` so lines stay space separated.
fn esc(s: &str) -> String {
    let mut o = String::new();
    for b in s.bytes() {
        if b <= b' ' || b == b'\\' || b == b'|' || b >= 0x7f {
            o.push_str(&format!("\\x{b:02x}"));
        } else {
            o.push(b as char);
        }
    }
    if o.is_empty() {
        o.push_str("\\-");
    }
    o
}

pub fn run() {
    if std::env::var("TEXT_VECTORS_GEN").is_ok_and(|v| v == "unicode") {
        unicode_tables();
        return;
    }
    l13();
}

fn ranges(pred: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut v: Vec<(u32, u32)> = Vec::new();
    for u in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(u) else { continue };
        if pred(c) {
            match v.last_mut() {
                Some(l) if l.1 + 1 == u => l.1 = u,
                _ => v.push((u, u)),
            }
        }
    }
    v
}

fn unicode_tables() {
    println!("/* Rust 1.95 char property tables for src/text (generated by");
    println!(" * `TEXT_VECTORS_GEN=unicode rustref text-vectors`; do not edit by hand). */");
    println!("#include \"text/unicode.h\"\n");
    for (name, pred) in [
        ("NUMERIC", char::is_numeric as fn(char) -> bool),
        ("LOWER", char::is_lowercase as fn(char) -> bool),
        ("UPPER", char::is_uppercase as fn(char) -> bool),
    ] {
        let r = ranges(pred);
        println!("static const uint32_t {name}[][2] = {{");
        for (a, b) in &r {
            println!("    {{0x{a:X}, 0x{b:X}}},");
        }
        println!("}};\n");
    }
    // Simple lowercase mappings (one char to one char); the only multi-char one is U+0130.
    println!("static const uint32_t TOLOWER[][2] = {{");
    for u in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(u) else { continue };
        let l: Vec<char> = c.to_lowercase().collect();
        if l.len() == 1 && l[0] != c {
            println!("    {{0x{u:X}, 0x{:X}}},", l[0] as u32);
        } else if l.len() > 1 {
            eprintln!("multi-char lowercase: U+{u:04X} -> {:?}", l);
        }
    }
    println!("}};");
}

