/// A runtime face alias (`.PhotoCraft-face-<family id>-<index>`, see `FontDb::select_named_face`)
/// without its family id: that id is process-global state (fontique's FamilyId counter), so it
/// depends on what ran before. Other names unchanged.
pub(crate) fn face_alias_name(f: &str) -> String {
    match f.strip_prefix(".PhotoCraft-face-").and_then(|rest| rest.find('-').map(|i| &rest[i + 1..])) {
        Some(index) => format!(".PhotoCraft-face-{index}"),
        None => f.to_string(),
    }
}

pub(crate) fn hash_layout(l: &TextLayout) -> [u64; 6] {
    let mut h = [H0; 6];
    for f in &l.faces {
        hu64(&mut h[0], f.font.data.as_ref().len() as u64);
        hu32(&mut h[0], f.font.index);
        hu32(&mut h[0], f.coords.len() as u32);
        for c in &f.coords {
            fnv(&mut h[0], &c.to_le_bytes());
        }
        hf32(&mut h[0], f.size_px);
        fnv(&mut h[0], &[u8::from(f.embolden)]);
        hf32(&mut h[0], f.skew_deg);
    }
    for g in &l.glyphs {
        hu32(&mut h[1], g.face);
        hu32(&mut h[1], g.id);
        hf32(&mut h[1], g.x);
        hf32(&mut h[1], g.y);
        hu32(&mut h[1], g.style);
        fnv(&mut h[1], &[g.orient as u8]);
    }
    for d in &l.decorations {
        for v in [d.x0, d.y0, d.x1, d.y1] {
            hf32(&mut h[2], v);
        }
        hu32(&mut h[2], d.style);
    }
    for li in &l.lines {
        hu64(&mut h[3], li.range.start as u64);
        hu64(&mut h[3], li.range.end as u64);
        for v in [li.baseline, li.x0, li.x1, li.ascent, li.descent] {
            hf32(&mut h[3], v);
        }
        hu64(&mut h[3], li.paragraph as u64);
    }
    for c in &l.clusters {
        hu64(&mut h[4], c.range.start as u64);
        hu64(&mut h[4], c.range.end as u64);
        hf32(&mut h[4], c.x);
        hf32(&mut h[4], c.advance);
        hu64(&mut h[4], c.line as u64);
        fnv(&mut h[4], &[u8::from(c.rtl)]);
    }
    for s in &l.styles {
        fnv(&mut h[5], face_alias_name(&s.font_family).as_bytes());
        hu32(&mut h[5], u32::from(s.weight));
        fnv(&mut h[5], &[u8::from(s.italic)]);
    }
    h
}

fn l14_detail(name: &str, l: &TextLayout) {
    if !std::env::var("TEXT_VECTORS_DETAIL").is_ok_and(|v| v == name) {
        return;
    }
    for (i, f) in l.faces.iter().enumerate() {
        println!("DF {i} len={} idx={} size={} emb={} skew={} coords={:?}", f.font.data.as_ref().len(), f.font.index, f.size_px, f.embolden, f.skew_deg, f.coords);
    }
    for g in &l.glyphs {
        println!("DG f={} id={} x={} y={} s={} o={}", g.face, g.id, g.x, g.y, g.style, g.orient as u8);
    }
    for c in &l.clusters {
        println!("DC {}..{} x={} a={} line={} rtl={}", c.range.start, c.range.end, c.x, c.advance, c.line, c.rtl);
    }
    for li in &l.lines {
        println!("DL {}..{} b={} x0={} x1={} a={} d={} p={}", li.range.start, li.range.end, li.baseline, li.x0, li.x1, li.ascent, li.descent, li.paragraph);
    }
    for d in &l.decorations {
        println!("DD {} {} {} {} {}", d.x0, d.y0, d.x1, d.y1, d.style);
    }
}

fn hash_opt4(h: &mut u64, b: Option<[f32; 4]>) {
    match b {
        None => fnv(h, &[0]),
        Some(b) => {
            fnv(h, &[1]);
            for v in b {
                hf32(h, v);
            }
        }
    }
}

fn l14_nav(name: &str, l: &TextLayout, text: &str) {
    let mut h = H0;
    hash_opt4(&mut h, l.bounds());
    hash_opt4(&mut h, l.line_bounds());
    // Carets at every byte offset (non-boundaries included: they fall through to the line end).
    for b in 0..=text.len() + 1 {
        let (x, t, bo) = l.caret(b);
        for v in [x, t, bo] {
            hf32(&mut h, v);
        }
        for (px, py) in l.caret_segment(b) {
            hf32(&mut h, px);
            hf32(&mut h, py);
        }
        hu64(&mut h, tl::line_index(l, b) as u64);
        hu64(&mut h, tl::char_index(text, b) as u64);
    }
    // Hit tests on a grid around the bounds.
    let b = l.bounds().unwrap_or([0.0, 0.0, 0.0, 0.0]);
    for iy in 0..9 {
        for ix in 0..9 {
            let x = b[0] - 10.0 + (b[2] - b[0] + 20.0) * ix as f32 / 8.0;
            let y = b[1] - 10.0 + (b[3] - b[1] + 20.0) * iy as f32 / 8.0;
            hu64(&mut h, l.hit_test(x, y) as u64);
            let (ci, li) = tl::hit_char(l, text, x, y);
            hu64(&mut h, ci as u64);
            hu64(&mut h, li as u64);
            fnv(&mut h, &[u8::from(tl::text_point_inside(l, x, y, 2.0))]);
        }
    }
    let n = text.chars().count();
    for i in 0..=n + 1 {
        hu64(&mut h, tl::byte_index(text, i) as u64);
        for fwd in [false, true] {
            hu64(&mut h, tl::word_boundary(text, i, fwd) as u64);
            hu64(&mut h, tl::line_edge(l, text, i, fwd) as u64);
        }
        let x = l.caret(tl::byte_index(text, i.min(n))).0;
        for dir in [-1, 1] {
            hu64(&mut h, tl::line_step(l, text, i, x, dir) as u64);
            hu64(&mut h, tl::line_step(l, text, i, x + 7.5, dir) as u64);
        }
    }
    println!("nav {name} {h:016x}");
}

/// serde_json writes non-finite floats as null; the case line carries them as fixes instead
/// (`R<run>.<field>=<bits>`, `P<para>.<field>=<bits>`, `S.<field>=<bits>`).
fn l14_sanitize(t: &mut TextLayer) -> String {
    let mut fixes: Vec<String> = Vec::new();
    let mut fix = |tag: String, v: &mut f32| {
        if !v.is_finite() {
            fixes.push(format!("{tag}={}", x32(*v)));
            *v = 0.0;
        }
    };
    for (i, r) in t.runs.iter_mut().enumerate() {
        let s = &mut r.style;
        fix(format!("R{i}.s"), &mut s.size_pt);
        fix(format!("R{i}.t"), &mut s.tracking);
        if let Some(l) = s.leading_pt.as_mut() {
            fix(format!("R{i}.l"), l);
        }
        fix(format!("R{i}.b"), &mut s.baseline_shift_pt);
        fix(format!("R{i}.h"), &mut s.horizontal_scale);
        fix(format!("R{i}.v"), &mut s.vertical_scale);
        fix(format!("R{i}.k"), &mut s.kern);
    }
    for (i, p) in t.paragraphs.iter_mut().enumerate() {
        let s = &mut p.style;
        fix(format!("P{i}.fi"), &mut s.first_line_indent_pt);
        fix(format!("P{i}.si"), &mut s.start_indent_pt);
        fix(format!("P{i}.ei"), &mut s.end_indent_pt);
        fix(format!("P{i}.sb"), &mut s.space_before_pt);
        fix(format!("P{i}.sa"), &mut s.space_after_pt);
        fix(format!("P{i}.al"), &mut s.auto_leading);
    }
    if let TextShape::Box { x, y, width, height } = &mut t.shape {
        fix("S.x".into(), x);
        fix("S.y".into(), y);
        fix("S.w".into(), width);
        fix("S.h".into(), height);
    }
    if fixes.is_empty() { "-".into() } else { fixes.join(",") }
}

fn l14_case_line(c: &L14Case) {
    let mut sane = c.layer.clone();
    let fixes = l14_sanitize(&mut sane);
    let t = &sane;
    let warp = match &t.warp {
        None => "-".to_string(),
        Some(w) => json_hex!(w),
    };
    println!(
        "case {} {} {} {} {} {} {} {} {} {} {fixes}",
        c.name,
        c.eng,
        x32(c.dpi),
        hex(t.text.as_bytes()),
        json_hex!(&t.runs),
        json_hex!(&t.paragraphs),
        json_hex!(&t.shape),
        json_hex!(&t.orientation),
        warp,
        t.transform.m.iter().map(|v| x64(*v)).collect::<Vec<_>>().join(":")
    );
}

