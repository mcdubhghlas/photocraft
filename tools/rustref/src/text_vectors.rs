fn hex(b: &[u8]) -> String {
    if b.is_empty() {
        return "-".into();
    }
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// The files `FontDb::load_system_fonts` scans (same walk: depth 8, ttf/otf/ttc/otc).
fn collect(out: &mut Vec<String>) {
    fn walk(dir: &std::path::Path, depth: u32, out: &mut Vec<String>) {
        let Ok(rd) = std::fs::read_dir(dir) else { return };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                if depth < 8 {
                    walk(&p, depth + 1, out);
                }
            } else if p.extension().and_then(|x| x.to_str()).is_some_and(|x| matches!(x.to_ascii_lowercase().as_str(), "ttf" | "otf" | "ttc" | "otc")) {
                out.push(p.display().to_string());
            }
        }
    }
    let home = std::env::var_os("HOME").map(std::path::PathBuf::from);
    let mut dirs: Vec<std::path::PathBuf> =
        ["/usr/share/fonts", "/usr/local/share/fonts", "/run/host/fonts", "/run/host/user-fonts"].iter().map(std::path::PathBuf::from).collect();
    if let Some(d) = std::env::var_os("XDG_DATA_HOME") {
        dirs.push(std::path::PathBuf::from(d).join("fonts"));
    }
    if let Some(h) = &home {
        dirs.push(h.join(".local/share/fonts"));
        dirs.push(h.join(".fonts"));
    }
    for d in dirs {
        walk(&d, 0, out);
    }
}

