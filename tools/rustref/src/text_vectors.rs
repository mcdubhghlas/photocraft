fn dump_layout(id: usize, spec_of: &dyn Fn(&GlyphFace) -> Option<String>, l: &TextLayout) -> Option<Dumped> {
    println!("L {id} {} {}", x32(l.px_per_pt), u8::from(l.vertical));
    for f in &l.faces {
        let spec = spec_of(f)?;
        let coords = if f.coords.is_empty() { "-".to_string() } else { f.coords.iter().map(|c| c.to_string()).collect::<Vec<_>>().join(",") };
        println!("LF {id} {} {} {} {} {} {coords}", esc(&spec), f.font.index, x32(f.size_px), u8::from(f.embolden), x32(f.skew_deg));
    }
    for g in &l.glyphs {
        let o = match g.orient {
            GlyphOrient::Horizontal => 0,
            GlyphOrient::Upright => 1,
            GlyphOrient::Rotated => 2,
        };
        println!("LG {id} {} {} {} {} {} {o}", g.face, g.id, x32(g.x), x32(g.y), g.style);
    }
    for d in &l.decorations {
        println!("LD {id} {} {} {} {} {}", x32(d.x0), x32(d.y0), x32(d.x1), x32(d.y1), d.style);
    }
    for s in &l.styles {
        let c = &s.color;
        let mode = match c.mode {
            ColorMode::Rgb => 0,
            ColorMode::Grayscale => 1,
            ColorMode::Cmyk => 2,
            ColorMode::Lab => 3,
            _ => 9,
        };
        println!(
            "LS {id} {mode} {} {} {} {} {} {} {} {} {} {}",
            x32(c.c[0]),
            x32(c.c[1]),
            x32(c.c[2]),
            x32(c.c[3]),
            x32(c.alpha),
            x32(s.horizontal_scale),
            x32(s.vertical_scale),
            x32(s.baseline_shift_pt),
            u8::from(s.faux_bold),
            u8::from(s.faux_italic)
        );
    }
    for li in &l.lines {
        println!("LL {id} {} {} {} {} {}", x32(li.x0), x32(li.x1), x32(li.baseline), x32(li.ascent), x32(li.descent));
    }
    Some(Dumped { id })
}

fn fmt_name(f: &PixelFormat) -> &'static str {
    match (f.mode, f.sample, f.alpha) {
        (ColorMode::Rgb, SampleType::U8, _) => "rgba8",
        (ColorMode::Rgb, SampleType::U16, _) => "rgba16",
        (ColorMode::Rgb, SampleType::F32, _) => "rgba32f",
        (ColorMode::Grayscale, SampleType::U8, _) => "graya8",
        (ColorMode::Cmyk, SampleType::U8, _) => "cmyka8",
        (ColorMode::Lab, SampleType::U16, _) => "laba16",
        _ => "other",
    }
}

