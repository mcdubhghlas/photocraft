/// Synthetic TrueType collection of the given fonts (table offsets rebased).
fn make_ttc(fonts: &[&[u8]]) -> Vec<u8> {
    let head = 12 + 4 * fonts.len();
    let mut out = Vec::new();
    out.extend_from_slice(b"ttcf");
    out.extend_from_slice(&0x0001_0000u32.to_be_bytes());
    out.extend_from_slice(&(fonts.len() as u32).to_be_bytes());
    let mut offs = Vec::new();
    let mut at = (head + 3) & !3;
    for f in fonts {
        offs.push(at);
        at += (f.len() + 3) & !3;
    }
    for o in &offs {
        out.extend_from_slice(&(*o as u32).to_be_bytes());
    }
    for (f, &base) in fonts.iter().zip(&offs) {
        out.resize(base, 0);
        let mut b = f.to_vec();
        let n = u16::from_be_bytes([b[4], b[5]]) as usize;
        for i in 0..n {
            let p = 12 + 16 * i + 8;
            let o = u32::from_be_bytes([b[p], b[p + 1], b[p + 2], b[p + 3]]) + base as u32;
            b[p..p + 4].copy_from_slice(&o.to_be_bytes());
        }
        out.extend_from_slice(&b);
    }
    out
}

