//! L13-L15 text reference vectors (`rustref text-vectors`). Owned by those chunks' ports: one
//! section per chunk (`# l13`, then `# l14`, `# l15` appended by later chunks), each printing
//! tab-free, space-separated lines that tests/text/test_parity.c replays.
//!
//! `TEXT_VECTORS_GEN=unicode rustref text-vectors` prints src/text/unicode_tables.c instead
//! (Rust 1.95's char::is_numeric / is_lowercase / is_uppercase / to_lowercase tables).
//!
//! Floats are printed as hex bits (f32 `%08x`, f64 `%016x`); hashes are FNV-1a 64 over the
//! little-endian bytes of the values listed at each line kind.

