fn print_resolved(tag: &str, ps: &str, r: &fonts::ResolvedFont) {
    println!("{tag} {} => {} {} {} {}", esc(ps), esc(&r.family), r.weight, u8::from(r.italic), u8::from(r.exact));
}

fn print_faces(db: &mut FontDb, fam: &str) {
    let faces = db.faces(fam);
    let mut s = String::new();
    for f in &faces {
        s.push_str(&format!(" {}:{}:{}", x32(f.weight), u8::from(f.italic), f.axes.len()));
        for (t, a, b, c) in &f.axes {
            s.push_str(&format!(":{}:{}:{}:{}", esc(t), x32(*a), x32(*b), x32(*c)));
        }
    }
    println!("faces {} =>{s}", esc(fam));
}

fn print_charmap(db: &mut FontDb, fam: &str, w: u16, it: bool) {
    let cm = db.charmap(fam, w, it);
    let mut h = H0;
    for c in &cm {
        hu32(&mut h, *c as u32);
    }
    let first = cm.first().map_or(0, |c| *c as u32);
    let last = cm.last().map_or(0, |c| *c as u32);
    println!("charmap {} {w} {} => {} {first:x} {last:x} {h:016x}", esc(fam), u8::from(it), cm.len());
}

