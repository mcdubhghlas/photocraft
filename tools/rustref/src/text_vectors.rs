/// A one-face layout skeleton for `spec`'s face `index` (None when layout picked another font).
fn face_for(engine: &mut TextEngine, bytes: &[u8], want_index: u32) -> Option<GlyphFace> {
    face_for_style(engine, bytes, want_index).map(|x| x.0)
}

/// The face plus the (family, weight, italic) that selects it.
fn face_for_style(engine: &mut TextEngine, bytes: &[u8], want_index: u32) -> Option<(GlyphFace, String, u16, bool)> {
    let names = engine.fonts.register_font_data(bytes.to_vec());
    for n in names {
        for f in engine.fonts.faces(&n) {
            let w = f.weight.round() as u16;
            let cm = engine.fonts.charmap(&n, w, f.italic);
            let Some(ch) = cm.iter().copied().find(|c| c.is_alphanumeric()).or(cm.iter().copied().find(|c| *c != ' ')) else { continue };
            let style = CharStyle { font_family: n.clone(), weight: w, italic: f.italic, size_pt: 10.0, ligatures: false, kerning: Kerning::Off, ..Default::default() };
            let text = ch.to_string();
            let layer = TextLayer { runs: vec![TextRun { len: text.len(), style }], text, ..Default::default() };
            let l = engine.layout(&layer, 72.0);
            for face in &l.faces {
                if face.font.data.as_ref() == bytes && face.font.index == want_index {
                    return Some((face.clone(), n.clone(), w, f.italic));
                }
            }
        }
    }
    None
}

fn hash_els(h: &mut u64, els: &[PathEl]) {
    for e in els {
        match e {
            PathEl::MoveTo(p) => {
                fnv(h, &[0]);
                hf64(h, p[0]);
                hf64(h, p[1]);
            }
            PathEl::LineTo(p) => {
                fnv(h, &[1]);
                hf64(h, p[0]);
                hf64(h, p[1]);
            }
            PathEl::QuadTo(a, p) => {
                fnv(h, &[2]);
                for q in [a, p] {
                    hf64(h, q[0]);
                    hf64(h, q[1]);
                }
            }
            PathEl::CurveTo(a, b, p) => {
                fnv(h, &[3]);
                for q in [a, b, p] {
                    hf64(h, q[0]);
                    hf64(h, q[1]);
                }
            }
            PathEl::Close => fnv(h, &[4]),
        }
    }
}

fn single_glyph_layout(face: &GlyphFace, gid: u32) -> TextLayout {
    TextLayout {
        faces: vec![face.clone()],
        glyphs: vec![PlacedGlyph { face: 0, id: gid, x: 0.0, y: 0.0, style: 0, orient: GlyphOrient::Horizontal }],
        styles: vec![CharStyle::default()],
        px_per_pt: 1.0,
        ..Default::default()
    }
}

fn l13_outlines_and_optical() {
    const SAMPLE: &str = "HHOOHnnoonvAVTAToTyLTWaYoPAFAVaxyrnilHIOHnHoxoxcdbpkkwwAAVVff1471LYTeKOnHeHaHsHtHgHzHkHxHvHwrst";
    for (spec, bytes) in font_files() {
        let count = fonts::face_count(&bytes).max(1);
        for index in 0..count as u32 {
            let mut engine = TextEngine::new();
            let Some((face, fam, fw, fit)) = face_for_style(&mut engine, &bytes, index) else {
                println!("noface {} {index}", esc(&spec));
                continue;
            };
            let var = spec.contains("Variable");
            let coord_sets: Vec<Vec<i16>> = if var { vec![vec![], vec![8192], vec![-16384]] } else { vec![vec![]] };
            for coords in coord_sets {
                let cs = if coords.is_empty() { "-".to_string() } else { coords.iter().map(|c| c.to_string()).collect::<Vec<_>>().join(",") };
                for size in [0.25f32, 1.0, 13.0, 37.5, 200.0, 3000.0] {
                    let mut f = face.clone();
                    f.coords = coords.clone();
                    f.size_px = size;
                    let (mut h, mut n, mut nonempty) = (H0, 0u32, 0u32);
                    for gid in 0..700u32 {
                        let els = render::outlines(&single_glyph_layout(&f, gid), &Affine::IDENTITY, None);
                        let els = els.into_iter().next().unwrap_or_default();
                        hu32(&mut h, gid);
                        hu32(&mut h, els.len() as u32);
                        hash_els(&mut h, &els);
                        n += 1;
                        if !els.is_empty() {
                            nonempty += 1;
                        }
                        if size == 37.5 && gid < 40 {
                            let mut g = H0;
                            hash_els(&mut g, &els);
                            println!("outg {} {index} {cs} {gid} => {} {g:016x}", esc(&spec), els.len());
                        }
                    }
                    println!("outl {} {index} {cs} {} => {n} {nonempty} {h:016x}", esc(&spec), x32(size));
                }
                // Optical kerning of SAMPLE's pairs (glyph ids through per-character layout).
                let mut gids = Vec::new();
                for c in SAMPLE.chars() {
                    let gid = (|| {
                        let text = c.to_string();
                        let style = CharStyle { font_family: fam.clone(), weight: fw, italic: fit, size_pt: 10.0, ligatures: false, kerning: Kerning::Off, ..Default::default() };
                        let layer = TextLayer { runs: vec![TextRun { len: text.len(), style }], text, ..Default::default() };
                        let l = engine.layout(&layer, 72.0);
                        let g = l.glyphs.first()?;
                        let fc = l.faces.get(g.face as usize)?;
                        (fc.font.data.as_ref() == &bytes[..] && fc.font.index == index).then_some(g.id)
                    })();
                    gids.push(gid);
                }
                println!(
                    "opticalgids {} {index} => {}",
                    esc(&spec),
                    gids.iter().map(|g| g.map_or("-".to_string(), |g| g.to_string())).collect::<Vec<_>>().join(" ")
                );
                let mut cache = optical::Cache::default();
                let mut line = String::new();
                for w in gids.windows(2) {
                    let v = match (w[0], w[1]) {
                        (Some(a), Some(b)) => cache.pair(1, &bytes, index, &[], a, b).map_or("none".to_string(), x32),
                        _ => "nochar".to_string(),
                    };
                    line.push(' ');
                    line.push_str(&v);
                }
                if coords.is_empty() {
                    println!("optical {} {index} =>{line}", esc(&spec));
                    let mut h = H0;
                    let mut cache = optical::Cache::default();
                    for a in 0..48u32 {
                        for b in 0..48u32 {
                            match cache.pair(7, &bytes, index, &[], a, b) {
                                Some(k) => hf32(&mut h, k),
                                None => fnv(&mut h, b"-"),
                            }
                        }
                    }
                    println!("opticalgrid {} {index} => {h:016x}", esc(&spec));
                }
            }
        }
    }
}

fn l13_optical_math() {
    for s in [-1.0f32, 0.0, 1.0, 12.0, 15.0, 24.0, 48.0, 94.9, 95.0, 100.0, 1e9, f32::NAN, f32::INFINITY] {
        println!("sizeadj {} => {}", x32(s), x32(optical::size_adjust(s)));
    }
    for (f, r) in [((0.1f32, 0.02f32), (0.12f32, 0.01f32)), ((0.0, 0.0), (0.2, 0.04)), ((0.5, 0.0), (0.05, 0.03)), ((f32::NAN, 0.0), (0.1, 0.1)), ((-2.0, 0.0), (2.0, 0.0)), ((2.0, 0.0), (-2.0, 0.0))] {
        println!("kernff {} {} {} {} => {}", x32(f.0), x32(f.1), x32(r.0), x32(r.1), x32(optical::kern_from_features(f, r)));
    }
    for i in [0usize, 1, 23, 47] {
        println!("sampley {i} => {}", x32(optical::sample_y(i)));
    }
    // pair_features over synthetic profiles.
    let mut rng = 0x1234_5678_9abc_def0u64;
    let mut next = || {
        rng ^= rng << 13;
        rng ^= rng >> 7;
        rng ^= rng << 17;
        ((rng >> 40) as f32) / (1u64 << 24) as f32
    };
    for case in 0..6 {
        let mut mk = |holes: bool| {
            let mut p = optical::Profile { left: [None; optical::SAMPLES], right: [None; optical::SAMPLES], advance: 0.6 };
            for i in 0..optical::SAMPLES {
                if holes && next() < 0.3 {
                    continue;
                }
                p.left[i] = Some(next() * 0.3 - 0.05);
                p.right[i] = Some(next() * 0.3 - 0.05);
            }
            p
        };
        let (l, r) = (mk(case % 2 == 1), mk(case >= 3));
        let mut s = String::new();
        for p in [&l, &r] {
            for side in [&p.left, &p.right] {
                for v in side.iter() {
                    s.push(' ');
                    s.push_str(&v.map_or("-".to_string(), x32));
                }
            }
        }
        let f = optical::pair_features(&l, &r);
        let res = f.map_or("none".to_string(), |(a, b)| format!("{} {}", x32(a), x32(b)));
        println!("pairf{s} => {res}");
    }
}

fn l13_coverage() {
    let mut rng = 0x9e37_79b9_7f4a_7c15u64;
    let mut next = || {
        rng ^= rng << 13;
        rng ^= rng >> 7;
        rng ^= rng << 17;
        (rng >> 11) as f64 / (1u64 << 53) as f64
    };
    for case in 0..40 {
        let (w, h) = match case % 5 {
            0 => (1usize, 1usize),
            1 => (7, 5),
            2 => (32, 32),
            3 => (100, 3),
            _ => (3, 64),
        };
        let mut c = Coverage::new(w, h);
        let mut s = String::new();
        let nl = 3 + case % 9;
        for i in 0..nl {
            let span = if case % 4 == 0 { 3.0 } else { 1.2 };
            let mut p = [0.0f64; 4];
            for (k, v) in p.iter_mut().enumerate() {
                let lim = if k % 2 == 0 { w as f64 } else { h as f64 };
                *v = (next() * span - (span - 1.0) / 2.0) * lim;
            }
            if case == 7 && i == 1 {
                p[0] = f64::NAN;
            }
            if case == 8 && i == 0 {
                p[1] = p[3];
            }
            if case == 9 && i == 2 {
                p = [1e300, -1e300, -1e300, 1e300];
            }
            if case == 11 && i == 0 {
                p = [2.5, -1e12, 2.5, 1e12];
            }
            c.line((p[0], p[1]), (p[2], p[3]));
            for v in p {
                s.push(' ');
                s.push_str(&x64(v));
            }
        }
        let v = c.finish();
        let mut hh = H0;
        for x in &v {
            hf32(&mut hh, *x);
        }
        println!("cov {w} {h}{s} => {hh:016x}");
    }
    // Bounds and rect_to.
    let mut b = Bounds::default();
    rect_to(&mut b, &Xform([0.5, 0.25, -1.0, 2.0, 3.0, -4.0]), 1.0, 2.0, 5.0, 9.5);
    b.add((f64::NAN, 1.0));
    let r = b.rect.unwrap_or([0.0; 4]);
    println!("bounds => {} {} {} {}", x64(r[0]), x64(r[1]), x64(r[2]), x64(r[3]));
    let m = Xform([1.5, -0.5, 0.25, 2.0, 10.0, -3.0]).mul(&Xform([0.0, 1.0, -1.0, 0.0, 4.0, 5.0]));
    println!("xmul => {}", m.0.iter().map(|v| x64(*v)).collect::<Vec<_>>().join(" "));
    println!("xscale => {}", x64(Xform([3.0, 4.0, 0.5, -0.5, 1.0, 1.0]).max_scale()));
}

