pc_algo_cr_encoding pc_algo_cr_encoding_of(float gamma)
{
    return isfinite(gamma) && gamma > 0.0f ? pc_clampf(gamma, 0.5f, 4.0f) : 0.0f;
}

float pc_algo_cr_decode(pc_algo_cr_encoding e, float v)
{
    return e > 0.0f ? powf(pc_rs_maxf_k(v, 0.0f), e) : pc_algo_photo_srgb_to_linear(v);
}

float pc_algo_cr_encode(pc_algo_cr_encoding e, float v)
{
    return e > 0.0f ? powf(pc_rs_maxf_k(v, 0.0f), 1.0f / e) : pc_algo_photo_linear_to_srgb(v);
}

static float luma3(const float c[3])
{
    return 0.2126f * c[0] + 0.7152f * c[1] + 0.0722f * c[2];
}

static float row_at(const float *row, float v)
{
    float p = pc_rs_maxf_k(v, 0.0f) * (float)(STEPS - 1), s;
    size_t j = pc_f32_to_size(p);
    j = j < STEPS - 2 ? j : STEPS - 2;
    s = p - (float)j;
    return row[j] + (row[j + 1] - row[j]) * s;
}

/* A curve row at a fractional internal amount x, at grey level v (both interpolated). */
static float curve(const float (*rows)[STEPS], size_t nrows, float from, float x, float v)
{
    float r, t;
    size_t i;
    if (v >= 1.0f) {
        return 1.0f;
    }
    r = pc_clampf((x - from) / 10.0f, 0.0f, (float)(nrows - 1));
    i = pc_f32_to_size(r);
    i = i < nrows - 2 ? i : nrows - 2;
    t = r - (float)i;
    return row_at(rows[i], v) * (1.0f - t) + row_at(rows[i + 1], v) * t;
}

float pc_algo_cr_whites_curve(float v, float x)
{
    return curve(WHITES, sizeof WHITES / sizeof WHITES[0], WHITES_FROM, x, v);
}

float pc_algo_cr_blacks_curve(float v, float x)
{
    return curve(BLACKS, sizeof BLACKS / sizeof BLACKS[0], BLACKS_FROM, x, v);
}

static void grid_index(const float *grid, size_t n, float v, size_t *i, float *t)
{
    size_t k;
    v = pc_clampf(v, grid[0], grid[n - 1]);
    *i = n - 2;
    for (k = 0; k + 1 < n; k++) {
        if (v <= grid[k + 1]) {
            *i = k;
            break;
        }
    }
    *t = (v - grid[*i]) / (grid[*i + 1] - grid[*i]);
}

/* Bilinear lookup of an adaptation table at black point bp and white point wp. */
static float adapt(const float (*table)[8], float bp, float wp)
{
    size_t i, j;
    float s, t, r0, r1;
    grid_index(BPS, 9, bp, &i, &s);
    grid_index(WPS, 8, wp, &j, &t);
    r0 = table[i][j] * (1.0f - t) + table[i][j + 1] * t;
    r1 = table[i + 1][j] * (1.0f - t) + table[i + 1][j + 1] * t;
    return r0 * (1.0f - s) + r1 * s;
}

void pc_algo_cr_wb_amounts(float whites, float blacks, float bp, float wp, float *xw, float *xb)
{
    float w = whites > 0.0f ? whites * adapt(AW, bp, wp) : whites;
    /* On photographs Photoshop's Blacks is about 1.2 times the block images' amount even where
     * their black point is 0 (ten public-domain photos: 1.08-1.36). */
    float b = blacks < 0.0f ? blacks * pc_rs_maxf_k(adapt(AB, bp, wp), PHOTO_BLACKS) : blacks;
    *xw = pc_clampf(w, -100.0f, 270.0f);
    *xb = pc_clampf(b, -100.0f, 100.0f);
}

static int cmp_total_f32(const void *pa, const void *pb)
{
    float a = *(const float *)pa, b = *(const float *)pb;
    int32_t ia, ib;
    memcpy(&ia, &a, 4);
    memcpy(&ib, &b, 4);
    ia ^= (int32_t)((uint32_t)(ia >> 31) >> 1);
    ib ^= (int32_t)((uint32_t)(ib >> 31) >> 1);
    return ia < ib ? -1 : (ia > ib ? 1 : 0);
}

static float percentile(float *v, size_t n, float q)
{
    qsort(v, n, sizeof *v, cmp_total_f32);
    return v[pc_f32_to_size(roundf((float)(n - 1) * q))];
}

/* The image's black and white points as sRGB-encoded grey levels: the 3rd percentile of the
 * luminance and the 99.5th of the brightest channel, on a copy at most 256 pixels across (so a
 * preview proxy and the full image agree). */
static pc_status luminance_points(const float (*px)[4], size_t w, size_t h, pc_algo_cr_encoding enc,
                                  float *bp, float *wp, pc_error *err)
{
    size_t m = w > h ? w : h, f = (m + 255) / 256, sw, sh, x, y, i, ncells = 0;
    double (*sum)[4];
    float *lum, *top;
    f = f > 1 ? f : 1;
    sw = (w + f - 1) / f;
    sh = (h + f - 1) / f;
    sum = pc_calloc_array(sw * sh > 0 ? sw * sh : 1, sizeof *sum);
    lum = pc_malloc_array(sw * sh > 0 ? sw * sh : 1, sizeof *lum);
    top = pc_malloc_array(sw * sh > 0 ? sw * sh : 1, sizeof *top);
    if (sum == NULL || lum == NULL || top == NULL) {
        free(sum), free(lum), free(top);
        return pc_fail(err, PC_ERR_NOMEM, "out of memory for Whites/Blacks");
    }
    for (y = 0; y < h; y++) {
        for (x = 0; x < w; x++) {
            const float *q = px[y * w + x];
            double *s = sum[(y / f) * sw + x / f];
            int c;
            for (c = 0; c < 3; c++) {
                s[c] += (double)pc_clampf(pc_algo_cr_decode(enc, q[c]), 0.0f, 1.0f);
            }
            s[3] += 1.0;
        }
    }
    for (i = 0; i < sw * sh; i++) {
        float c[3];
        int k;
        if (!(sum[i][3] > 0.0)) {
            continue;
        }
        for (k = 0; k < 3; k++) {
            c[k] = pc_f64_to_f32(sum[i][k] / sum[i][3]);
        }
        lum[ncells] = luma3(c);
        top[ncells] = pc_rs_maxf(pc_rs_maxf(c[0], c[1]), c[2]);
        ncells++;
    }
    if (ncells == 0) {
        *bp = 0.0f;
        *wp = 1.0f;
    } else {
        *bp = pc_algo_photo_linear_to_srgb(percentile(lum, ncells, 0.03f));
        *wp = pc_algo_photo_linear_to_srgb(percentile(top, ncells, 0.995f));
    }
    free(sum), free(lum), free(top);
    return PC_OK;
}

typedef struct wb_ctx {
    float (*px)[4];
    size_t w;
    float xw, xb;
    pc_algo_cr_encoding enc;
} wb_ctx;

/* A grey level's new level, both sRGB-encoded. */
static float grey(const wb_ctx *c, float v)
{
    v = c->xw != 0.0f ? pc_algo_cr_whites_curve(v, c->xw) : v;
    return c->xb != 0.0f ? pc_algo_cr_blacks_curve(v, c->xb) : v;
}

static pc_status wb_rows(void *vc, size_t chunk, size_t y0, size_t y1)
{
    const wb_ctx *c = vc;
    bool per_channel = c->xw > 0.0f || c->xb < 0.0f;
    size_t i;
    (void)chunk;
    for (i = y0 * c->w; i < y1 * c->w; i++) {
        float *q = c->px[i], lin[3];
        int k;
        for (k = 0; k < 3; k++) {
            lin[k] = pc_algo_cr_decode(c->enc, q[k]);
        }
        if (per_channel) {
            for (k = 0; k < 3; k++) {
                float over = pc_rs_maxf_k(lin[k] - 1.0f, 0.0f);
                q[k] = pc_algo_cr_encode(
                    c->enc, pc_algo_photo_srgb_to_linear(
                                grey(c, pc_algo_photo_linear_to_srgb(pc_rs_minf_k(lin[k], 1.0f)))) +
                                over);
            }
        } else {
            float y = pc_rs_maxf_k(luma3(lin), 0.0f), y2, kk;
            if (y <= 1e-7f) {
                continue;
            }
            y2 = pc_algo_photo_srgb_to_linear(grey(c, pc_algo_photo_linear_to_srgb(pc_rs_minf_k(y, 1.0f)))) +
                 pc_rs_maxf_k(y - 1.0f, 0.0f);
            kk = y2 / y;
            for (k = 0; k < 3; k++) {
                q[k] = pc_algo_cr_encode(c->enc, lin[k] * kk);
            }
        }
    }
    return PC_OK;
}

pc_status pc_algo_cr_whites_blacks(float (*px)[4], size_t w, size_t h, float whites, float blacks,
                                   pc_algo_cr_encoding enc, pc_error *err)
{
    float bp, wp;
    wb_ctx c;
    pc_status st = luminance_points((const float (*)[4])px, w, h, enc, &bp, &wp, err);
    if (st != PC_OK) {
        return st;
    }
    pc_algo_cr_wb_amounts(pc_clampf(whites, -100.0f, 100.0f), pc_clampf(blacks, -100.0f, 100.0f), bp, wp,
                          &c.xw, &c.xb);
    if (c.xw == 0.0f && c.xb == 0.0f) {
        return PC_OK;
    }
    c.px = px;
    c.w = w;
    c.enc = enc;
    st = pc_algo_par_for(h, 4, wb_rows, &c);
    return st == PC_OK ? PC_OK : pc_fail(err, st, "Whites/Blacks failed");
}
